"""Cell-number distribution per donor for the three PsychAD subtypes (used to compare the cell-number distributions behind the PBw result).
Reads pop/pop_P{1,2,3}_meta.npz (gitignored; directory in env FEWDONOR_POP, default ../pop) and writes paper2/celldist_summary.json and paper2/celldist_nums.tex.
If the .npz files are absent the committed celldist_summary.json is used and celldist_nums.tex is regenerated from it.
Usage: python paper2/make_celldist.py"""
import os, json, numpy as np
HERE = os.path.dirname(os.path.abspath(__file__)); POP = os.environ.get("FEWDONOR_POP", os.path.join(HERE, "..", "pop"))
SJ = os.path.join(HERE, "celldist_summary.json"); SUBS = ("P1", "P2", "P3"); NAMES = {"P1": "Homeo\\_CECR2", "P2": "PVM\\_CD163", "P3": "ADAM\\_GPNMB"}
if all(os.path.exists(os.path.join(POP, f"pop_{s}_meta.npz")) for s in SUBS):
    S = {}
    for s in SUBS:
        d = np.load(os.path.join(POP, f"pop_{s}_meta.npz"), allow_pickle=True)["donor"].astype(str)
        _, n = np.unique(d, return_counts=True); n = n[n >= 4].astype(float)       # donors with at least 4 nuclei, as in every analysis
        S[s] = dict(donors=int(len(n)), nuclei=int(n.sum()), median=float(np.median(n)), q25=float(np.percentile(n, 25)), q75=float(np.percentile(n, 75)),
                    frac_lt10=float((n < 10).mean()), frac_ge100=float((n >= 100).mean()), cv=float(n.std() / n.mean()),
                    mean_inv_n=float((1 / n).mean()), eff_donors_frac=float(n.sum() ** 2 / (n ** 2).sum() / len(n)))
    json.dump(S, open(SJ, "w"), indent=1)
else:
    S = json.load(open(SJ))
pc = lambda x: f"{100 * x:.0f}\\%"
M = {"CdLtTenPVM": pc(S["P2"]["frac_lt10"]),
     "CdLtTenOthers": f"{pc(S['P1']['frac_lt10'])} and {pc(S['P3']['frac_lt10'])}", "CdMedPVM": f"{S['P2']['median']:.0f}",
     "CdMedOthers": f"{S['P1']['median']:.0f} and {S['P3']['median']:.0f}"}
open(os.path.join(HERE, "celldist_nums.tex"), "w").write("% generated by make_celldist.py from celldist_summary.json\n" + "".join(f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in M.items()))
print(M)
