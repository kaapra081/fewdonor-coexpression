"""Plan 8 macros: python paper2/make_plan8.py -> paper2/plan8nums.tex (reads rev5/out/plan8_summary.json and rev4/out/R2_*.json)."""
import os, json, glob, numpy as np
from scipy.stats import beta
HERE = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(HERE, "..")
s = json.load(open(os.path.join(R, "rev5", "out", "plan8_summary.json"))); M = {}
def cp(k, n): return (beta.ppf(0.025, k, n - k + 1) if k else 0.0, beta.ppf(0.975, k + 1, n - k) if k < n else 1.0)
A, B, C = s["8A"], s["8B"], s["8C"]
M["PeLAh"] = f"{A['LA_LM']['XDSMh']['runs_with_call']}, {A['LA_FC']['XDSMh']['runs_with_call']}"
M["PeLAx"] = f"{A['LA_LM']['XDSM']['runs_with_call']}, {A['LA_FC']['XDSM']['runs_with_call']}"
M["PeLAhtI"] = f"{A['LA_LM']['XDSMh']['mean_t05']:.3f}, {A['LA_FC']['XDSMh']['mean_t05']:.3f}"
M["PeLAhFCmax"] = str(A["LA_FC"]["XDSMh"]["max_calls"])
M["PeLDh"] = f"{A['LD_LM']['XDSMh']['runs_with_call']}, {A['LD_FC']['XDSMh']['runs_with_call']}"
M["PeLDhMean"] = f"{A['LD_LM']['XDSMh']['mean_calls']:,.0f}".replace(",", "{,}") + f", {A['LD_FC']['XDSMh']['mean_calls']:.1f}"
M["PeLRh"] = f"{A['LR_LM']['XDSMh']:,}".replace(",", "{,}"); M["PeLRkeep"] = f"{100*A['LR_LM']['keep']:.0f}\\%"
M["PeLRisg"] = f"{A['LR_LM']['isg_XDSMh']} of {A['LR_LM']['isg_pairs']}"
M["PeBx"] = ", ".join(str(B[p]["XDSM"]["runs_with_call"]) for p in ("P1", "P2", "P3"))
M["PeBh"] = ", ".join(str(B[p]["XDSMh"]["runs_with_call"]) for p in ("P1", "P2", "P3"))
M["PeBhb"] = ", ".join(str(B[p]["XDSMhb"]["runs_with_call"]) for p in ("P1", "P2", "P3"))
M["PeBhbtI"] = f"{min(B[p]['XDSMhb']['mean_t05'] for p in ('P1','P2','P3')):.3f}--{max(B[p]['XDSMhb']['mean_t05'] for p in ('P1','P2','P3')):.3f}"
M["PeBhtI"] = f"{min(B[p]['XDSMh']['mean_t05'] for p in ('P1','P2','P3')):.3f}--{max(B[p]['XDSMh']['mean_t05'] for p in ('P1','P2','P3')):.3f}"
r2 = {p: [json.load(open(f))["all"] for f in glob.glob(os.path.join(R, "rev4", "out", f"R2_{p}_k*.json"))] for p in ("P1", "P2", "P3")}
M["PeBpb"] = ", ".join(str(sum(r["PB"]["V"] > 0 for r in r2[p])) for p in ("P1", "P2", "P3"))
M["PeBkx"] = ", ".join(str(sum(r["KX"]["V"] > 0 for r in r2[p])) for p in ("P1", "P2", "P3"))
k = 12 + A["LA_LM"]["XDSMh"]["runs_with_call"] + A["LA_FC"]["XDSMh"]["runs_with_call"]; n = 210 + A["LA_LM"]["XDSMh"]["n_runs"] + A["LA_FC"]["XDSMh"]["n_runs"]
lo, hi = cp(k, n); M["PeHk"], M["PeHn"], M["PeHpct"], M["PeHci"] = str(k), str(n), f"{100*k/n:.1f}\\%", f"{100*lo:.1f}--{100*hi:.1f}\\%"
def rng(m, q):
    v = [C[p][m][q]["mean"] for p in ("P1", "P2", "P3")]; return f"{min(v):.2f}--{max(v):.2f}" if q != "power_at_fdp0.05" or m != "PB" else f"{min(v):.3f}--{max(v):.3f}"
for m, tag in (("PB", "PB"), ("KX", "KX"), ("XDSM", "X"), ("XDSMh", "H")):
    M[f"PeMatch{tag}"] = rng(m, "power_at_fdp0.05"); M[f"PeMatchTen{tag}"] = rng(m, "power_at_fdp0.10")
M["PeMatchPBmax"] = f"{max(C[p]['PB']['power_at_fdp0.05']['mean'] for p in ('P1','P2','P3')):.3f}"
M["PeMatchXlist"] = ", ".join(f"{C[p]['XDSM']['power_at_fdp0.05']['mean']:.2f}" for p in ("P1", "P2", "P3"))
M["PeMatchHlist"] = ", ".join(f"{C[p]['XDSMh']['power_at_fdp0.05']['mean']:.2f}" for p in ("P1", "P2", "P3"))
M["PeMatchSDmax"] = f"{max(C[p][m]['power_at_fdp0.05']['sd'] for p in ('P1','P2','P3') for m in ('XDSM','XDSMh')):.2f}"
M["PeSha"] = s["plan_sha256"][:16]
M["PeLAhSum"] = str(A["LA_LM"]["XDSMh"]["runs_with_call"] + A["LA_FC"]["XDSMh"]["runs_with_call"])
M["PeMatchPBpct"] = f"{100*max(C[p]['PB']['power_at_fdp0.05']['mean'] for p in ('P1','P2','P3')):.1f}\\%"
open(os.path.join(HERE, "plan8nums.tex"), "w").write("% generated by make_plan8.py from rev5/out/plan8_summary.json; do not edit\n" + "".join(f"\\newcommand{{\\{k_}}}{{{v}}}\n" for k_, v in M.items()))
print(open(os.path.join(HERE, "plan8nums.tex")).read())
